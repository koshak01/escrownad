-- escrownad/seeds/wallets_pubkey.sql
-- Публичный ключ кошелька — основа для шифрования данных лично под человека.
--
--     psql -h 127.0.0.1 -U html -d 'escrownad.com' -f seeds/wallets_pubkey.sql
--
-- Зачем: адрес кошелька это односторонний хэш, зашифровать «для адреса»
-- нельзя. А вот публичный ключ восстанавливается из любой подписи — в том
-- числе из той, которой человек и так входит на сайт. Сохраняем его при
-- входе, чтобы потом можно было передать покупателю документы по сделке
-- так, что прочитает их только он: ни мы, ни кто-либо с доступом к базе.
--
-- Обратной силы нет: у тех, кто входил раньше, ключ появится при следующем
-- входе. Поэтому колонка nullable.

ALTER TABLE users2wallets ADD COLUMN IF NOT EXISTS u2w_pubkey varchar(70);

COMMENT ON COLUMN users2wallets.u2w_pubkey IS
    'Публичный ключ secp256k1 в сжатом виде (0x02/0x03 || x), восстановлен из подписи входа';
